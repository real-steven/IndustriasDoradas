import { createRequire } from "node:module";
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import process from "node:process";
import { format } from "prettier";

const root = resolve(import.meta.dirname, "..");
process.env.NODE_ENV = "test";
process.env.PORT = "3000";
process.env.SUPABASE_URL = "https://contract.invalid";
process.env.SUPABASE_SECRET_KEY = [
  "contract",
  "generation",
  "placeholder",
].join("-");

const require = createRequire(import.meta.url);
const { NestFactory } = require(
  resolve(root, "apps/api/node_modules/@nestjs/core"),
);
const { AppModule } = require(resolve(root, "apps/api/dist/app.module.js"));
const { configureApplication } = require(
  resolve(root, "apps/api/dist/app.setup.js"),
);
const { createOpenApiDocument } = require(
  resolve(root, "apps/api/dist/openapi/openapi.js"),
);

const app = await NestFactory.create(AppModule, { logger: false });
configureApplication(app);
await app.init();
const document = createOpenApiDocument(app);
await app.close();

if (
  !document.paths?.["/api/v1/auth/session"] ||
  !document.paths?.["/api/v1/organizations/{organizationId}/plants"]
) {
  throw new Error(
    "El contrato no contiene los endpoints mínimos para los clientes",
  );
}

const json = await format(JSON.stringify(sortObject(document)), {
  parser: "json",
});
const typescript = await format(generateTypeScriptClient(), {
  parser: "typescript",
});
const csharp = generateCSharpClient();
const outputs = [
  ["docs/openapi/openapi.json", json],
  ["apps/web/src/api/generated/api-client.ts", typescript],
  [
    "apps/desktop/src/IndustriasDoradas.Desktop/Generated/ApiClient.g.cs",
    csharp,
  ],
];

let stale = false;
for (const [relative, content] of outputs) {
  const path = resolve(root, relative);
  if (process.argv.includes("--check")) {
    const current = await readFile(path, "utf8").catch(() => "");
    if (current.replaceAll("\r\n", "\n") !== content.replaceAll("\r\n", "\n")) {
      console.error(`Contrato desactualizado: ${relative}`);
      stale = true;
    }
  } else {
    await mkdir(dirname(path), { recursive: true });
    await writeFile(path, content, "utf8");
    console.log(`Generado: ${relative}`);
  }
}
if (stale) process.exitCode = 1;

function sortObject(value) {
  if (Array.isArray(value)) return value.map(sortObject);
  if (value && typeof value === "object") {
    return Object.fromEntries(
      Object.keys(value)
        .sort()
        .map((key) => [key, sortObject(value[key])]),
    );
  }
  return value;
}

function generateTypeScriptClient() {
  return `// <auto-generated /> Generado por scripts/generate-contracts.mjs. No editar.
export type RoleCode = "JEFE_EMPRESA" | "ADMINISTRADOR" | "JEFE_PLANTA";
export interface Session { userId: string; sessionId: string; profileId: string; organizationId: string; role: RoleCode; issuedAt: string; expiresAt: string }
export interface CatalogItem { id: string; organizationId: string; code?: string; name: string; isActive: boolean; deactivatedAt: string | null; createdAt: string; updatedAt: string }
export interface PageCatalog { items: CatalogItem[]; page: number; pageSize: number; total: number; totalPages: number }
export interface ApiError { statusCode: number; code: string; message: string | string[]; path: string; timestamp: string; correlationId: string }
export class ApiClient {
  constructor(private readonly baseUrl: string, private readonly accessToken: () => string | null, private readonly transport: typeof fetch = fetch) {}
  getSession(signal?: AbortSignal): Promise<Session> { return this.request<Session>("/api/v1/auth/session", signal); }
  listPlants(organizationId: string, page = 1, pageSize = 25, signal?: AbortSignal): Promise<PageCatalog> {
    const query = new URLSearchParams({ page: String(page), pageSize: String(pageSize) });
    return this.request<PageCatalog>(\`/api/v1/organizations/\${encodeURIComponent(organizationId)}/plants?\${query}\`, signal);
  }
  private async request<T>(path: string, signal?: AbortSignal): Promise<T> {
    const token = this.accessToken();
    const response = await this.transport(\`\${this.baseUrl.replace(/\\\/$/u, "")}\${path}\`, { headers: token ? { Authorization: \`Bearer \${token}\` } : {}, signal });
    if (!response.ok) { const error = await response.json() as ApiError; throw Object.assign(new Error(Array.isArray(error.message) ? error.message.join(", ") : error.message), { details: error }); }
    return await response.json() as T;
  }
}
`;
}

